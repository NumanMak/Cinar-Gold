import re, urllib.request, os
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0.0.0 Safari/537.36"
URL = "https://fonts.googleapis.com/css2?family=Inter:ital,opsz,wght@0,14..32,100..900;1,14..32,100..900&display=swap"
def get(u):
    return urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": UA})).read()
css = get(URL).decode()
blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*{(.*?)}", css, re.S)
out = ["/* Inter variable (self-hosted, latin + latin-ext). Generated by tools/fonts.py */"]
ranges = {}
for subset, body in blocks:
    if subset not in ("latin", "latin-ext"): continue
    style = re.search(r"font-style:\s*(\w+)", body).group(1)
    src = re.search(r"url\((.*?)\)", body).group(1)
    ur = re.search(r"unicode-range:\s*(.*?);", body, re.S).group(1).strip()
    name = ("inter-italic-" if style == "italic" else "inter-") + subset + ".woff2"
    open(os.path.join("assets/fonts", name), "wb").write(get(src))
    ranges[name] = ur
    out.append(f"@font-face {{\n  font-family: 'Inter';\n  font-style: {style};\n  font-weight: 100 900;\n  font-display: swap;\n  src: url('../fonts/{name}') format('woff2');\n  unicode-range: {ur};\n}}")
open("assets/css/fonts.css", "w", encoding="utf-8").write("\n".join(out) + "\n")
def cov(ur, ch):
    c = ord(ch)
    for p in ur.split(","):
        p = p.strip()[2:]
        if "?" in p: lo, hi = int(p.replace("?", "0"), 16), int(p.replace("?", "F"), 16)
        elif "-" in p: lo, hi = (int(x, 16) for x in p.split("-"))
        else: lo = hi = int(p, 16)
        if lo <= c <= hi: return True
    return False
for ch in "ıİşŞğĞçÇöÖüÜ":
    print(ch, [n for n, u in ranges.items() if cov(u, ch)])
for n, u in ranges.items(): print(n, os.path.getsize("assets/fonts/" + n), u)
